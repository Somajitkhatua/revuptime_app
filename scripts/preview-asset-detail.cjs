const { chromium } = require('@playwright/test');
const path = require('path');
(async () => {
const browser = await chromium.launch({channel:'chrome',headless:true});
const page = await browser.newPage({viewport:{width:390,height:844}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:8082/login',{waitUntil:'networkidle'});
await page.getByRole('button',{name:'Sign In',exact:true}).click();
await page.getByText('Plant Health',{exact:true}).waitFor();
await page.getByText('Assets',{exact:true}).last().click();
await page.getByRole('button',{name:'Motor M-07, Critical, 43%',exact:true}).click();
await page.getByText('Current readings',{exact:true}).waitFor();
await page.waitForTimeout(700);
await page.screenshot({path:path.resolve('output/fourth-page-mobile.png'),fullPage:true});
await page.getByRole('tab',{name:'Trends',exact:true}).click();
await page.getByRole('button',{name:'Explore Trends',exact:true}).waitFor();
await page.getByRole('tab',{name:'Alerts',exact:true}).click();
await page.getByText('High radial vibration',{exact:true}).last().waitFor();
await page.getByRole('tab',{name:'Documents',exact:true}).click();
await page.getByRole('button',{name:'Manage Documents',exact:true}).waitFor();
await page.getByRole('tab',{name:'History',exact:true}).click();
await page.getByRole('button',{name:'Maintenance History',exact:true}).waitFor();
await page.getByRole('tab',{name:'Overview',exact:true}).click();
await page.getByText('SN-4078',{exact:true}).waitFor();
await page.getByRole('button',{name:'Go to Assets',exact:true}).click();
await page.getByRole('button',{name:'Motor M-07, Critical, 43%',exact:true}).waitFor();
if(errors.length) throw new Error(errors.join('\n'));
console.log(JSON.stringify({errors,tabs:'passed',readings:'passed',navigation:'passed'}));
await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
